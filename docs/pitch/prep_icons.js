// Render Lucide icons (react-icons) to PNG data URIs via sharp for pptxgenjs.
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const LU = require('react-icons/lu');

// icon key -> react-icons export name (verified at runtime)
const ICONS = {
  camera: 'LuCamera', scan: 'LuScanLine', shield: 'LuShieldCheck', mappin: 'LuMapPin',
  phone: 'LuPhone', calendar: 'LuCalendarDays', chart: 'LuChartLine', file: 'LuFileText',
  brain: 'LuBrain', wind: 'LuWind', book: 'LuBookOpen', search: 'LuSearch',
  sparkles: 'LuSparkles', flame: 'LuFlame', heart: 'LuHeartPulse', check: 'LuCircleCheck',
  alert: 'LuTriangleAlert', activity: 'LuActivity', sun: 'LuSun', chevron: 'LuChevronRight',
  stethoscope: 'LuStethoscope', clock: 'LuClock', target: 'LuTarget', layers: 'LuLayers',
  trending: 'LuTrendingUp', users: 'LuUsers',
};

const COLORS = {
  cream: 'F4EFE7', pine: '1E6E5C', coral: 'E0704F', slate: '55645C',
  ink: '202B26', palepine: 'D9EDE4', dark: '123F33', paleonpine: 'C8DBD2',
};

const SIZE = 512;

async function render(iconKey, colorKey) {
  const exportName = ICONS[iconKey];
  const Icon = LU[exportName];
  if (!Icon) throw new Error(`Missing react-icons export: ${exportName} (for ${iconKey})`);
  const svg = renderToStaticMarkup(
    React.createElement(Icon, { size: SIZE, color: '#' + COLORS[colorKey] })
  );
  const png = await sharp(Buffer.from(svg)).png().toBuffer();
  return 'data:image/png;base64,' + png.toString('base64');
}

(async () => {
  const out = {};
  const missing = [];
  const keys = Object.keys(ICONS);
  const colorKeys = ['cream', 'pine', 'coral', 'slate', 'ink', 'palepine', 'paleonpine'];
  for (const ik of keys) {
    for (const ck of colorKeys) {
      try {
        out[`${ik}_${ck}`] = await render(ik, ck);
      } catch (e) {
        missing.push(e.message);
      }
    }
  }
  if (missing.length) {
    console.error('MISSING:', missing.join('\n'));
    process.exit(1);
  }
  const js =
    '// Auto-generated by prep_icons.js — PNG data URIs for Lucide icons.\n' +
    'module.exports = ' + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(__dirname, 'icons.js'), js);
  console.log(`icons.js written: ${Object.keys(out).length} icon renders`);
})();
